//! `cargo make unicode <ucd-dir>`: generate `std/unicode.thx`, the case
//! tables behind `String.toLower` / `toUpper` / `ignoreCase:` (D195), which
//! std/string reads (D196).
//!
//! Reads `UnicodeData.txt`, `SpecialCasing.txt`, `CaseFolding.txt`, and
//! `DerivedCoreProperties.txt` from a Unicode Character Database directory
//! (https://www.unicode.org/Public/<ver>/ucd/).
//! Each mapping is a table of code points to one or more code points:
//!
//! - lower / upper: UnicodeData's simple mappings, overridden by
//!   SpecialCasing's unconditional ones (`ß` → `SS`); conditional entries
//!   (final sigma, Turkish, Lithuanian) are left out.
//! - fold: CaseFolding's full folding, statuses C and F (`ß` → `ss`).
//! - cased / caseIgnorable: DerivedCoreProperties' `Cased` and
//!   `Case_Ignorable`, as `first, last` pairs, for the final-sigma condition
//!   that `toLower` applies itself (D216).
//!
//! One-to-one mappings are stored as ranges (`first..=last` every `stride`
//! code points maps by `delta`), the rest as a short list of expansions; each
//! is a flat `Array<Int64>` of four numbers per entry.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

type Mapping = BTreeMap<u32, Vec<u32>>;

pub fn generate(ucd: &Path, out: &Path) -> Result<String, String> {
    let read = |name: &str| {
        fs::read_to_string(ucd.join(name)).map_err(|error| format!("{name}: {error}"))
    };
    let unicode_data = read("UnicodeData.txt")?;
    let special_casing = read("SpecialCasing.txt")?;
    let case_folding = read("CaseFolding.txt")?;
    let core_properties = read("DerivedCoreProperties.txt")?;

    let version = case_folding
        .lines()
        .next()
        .and_then(|line| line.strip_prefix("# CaseFolding-"))
        .and_then(|rest| rest.strip_suffix(".txt"))
        .ok_or("CaseFolding.txt: no version on its first line")?
        .to_string();

    let mut lower = Mapping::new();
    let mut upper = Mapping::new();
    for line in unicode_data.lines() {
        let fields: Vec<&str> = line.split(';').collect();
        if fields.len() < 15 {
            continue;
        }
        let code = parse_code(fields[0])?;
        if !fields[12].is_empty() {
            upper.insert(code, vec![parse_code(fields[12])?]);
        }
        if !fields[13].is_empty() {
            lower.insert(code, vec![parse_code(fields[13])?]);
        }
    }

    for line in special_casing.lines() {
        let data = line.split('#').next().unwrap_or("").trim();
        if data.is_empty() {
            continue;
        }
        let fields: Vec<&str> = data.split(';').map(str::trim).collect();
        // code; lower; title; upper; [conditions;]
        if fields.len() > 4 && !fields[4].is_empty() {
            continue;
        }
        let code = parse_code(fields[0])?;
        override_mapping(&mut lower, code, parse_codes(fields[1])?);
        override_mapping(&mut upper, code, parse_codes(fields[3])?);
    }

    let mut fold = Mapping::new();
    for line in case_folding.lines() {
        let data = line.split('#').next().unwrap_or("").trim();
        if data.is_empty() {
            continue;
        }
        let fields: Vec<&str> = data.split(';').map(str::trim).collect();
        if fields.len() < 3 || !matches!(fields[1], "C" | "F") {
            continue;
        }
        fold.insert(parse_code(fields[0])?, parse_codes(fields[2])?);
    }

    let mut text = format!(
        "## Generated by `cargo make unicode <ucd-dir>` from the Unicode {version}\n\
         ## Character Database (UnicodeData, SpecialCasing, CaseFolding,\n\
         ## DerivedCoreProperties). Do not edit.\n\
         ##\n\
         ## Case tables for String's methods in std/string (D195, D196). A range is\n\
         ## four numbers: first, last, delta, stride; the code points from first to\n\
         ## last, every stride, map to themselves plus delta. An expansion is four\n\
         ## numbers: a code point, then the up to three it maps to (0 when unused).\n\
         ## Both are sorted by their first number. A property is pairs of numbers,\n\
         ## first and last, sorted (D216).\n\
         \n\
         export let unicodeVersion = \"{version}\"\n"
    );
    let mut summary = format!("Unicode {version}:");
    for (name, mapping) in [("lower", &lower), ("upper", &upper), ("fold", &fold)] {
        let (ranges, expansions) = emit_table(&mut text, name, mapping)?;
        summary.push_str(&format!(" {name} {ranges} ranges + {expansions} expansions;"));
    }
    for (name, property) in [("cased", "Cased"), ("caseIgnorable", "Case_Ignorable")] {
        let ranges = property_ranges(&core_properties, property)?;
        if ranges.is_empty() {
            return Err(format!("DerivedCoreProperties.txt: no `{property}` entries"));
        }
        text.push_str(&format!("\nexport let {name}Ranges: Array<Int64> = [\n"));
        for (first, last) in &ranges {
            text.push_str(&format!("    0x{first:04X}, 0x{last:04X},\n"));
        }
        text.push_str("]\n");
        summary.push_str(&format!(" {name} {} ranges;", ranges.len()));
    }
    fs::write(out, text).map_err(|error| format!("{}: {error}", out.display()))?;
    Ok(summary)
}

/// The code points with `property`, as merged `first, last` ranges.
fn property_ranges(text: &str, property: &str) -> Result<Vec<(u32, u32)>, String> {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for line in text.lines() {
        let data = line.split('#').next().unwrap_or("").trim();
        let Some((codes, name)) = data.split_once(';') else {
            continue;
        };
        if name.trim() != property {
            continue;
        }
        let (first, last) = match codes.trim().split_once("..") {
            Some((first, last)) => (parse_code(first)?, parse_code(last)?),
            None => {
                let code = parse_code(codes)?;
                (code, code)
            }
        };
        ranges.push((first, last));
    }
    ranges.sort_unstable();
    let mut merged: Vec<(u32, u32)> = Vec::new();
    for (first, last) in ranges {
        match merged.last_mut() {
            Some(previous) if first <= previous.1 + 1 => previous.1 = previous.1.max(last),
            _ => merged.push((first, last)),
        }
    }
    Ok(merged)
}

fn parse_code(text: &str) -> Result<u32, String> {
    u32::from_str_radix(text.trim(), 16).map_err(|_| format!("bad code point `{text}`"))
}

fn parse_codes(text: &str) -> Result<Vec<u32>, String> {
    text.split_whitespace().map(parse_code).collect()
}

/// A SpecialCasing entry replaces the simple mapping; mapping to itself
/// removes it.
fn override_mapping(mapping: &mut Mapping, code: u32, to: Vec<u32>) {
    if to == [code] {
        mapping.remove(&code);
    } else {
        mapping.insert(code, to);
    }
}

fn emit_table(text: &mut String, name: &str, mapping: &Mapping) -> Result<(usize, usize), String> {
    let mut ranges: Vec<(u32, u32, i64, u32)> = Vec::new();
    let mut expansions: Vec<(u32, &[u32])> = Vec::new();
    for (&code, to) in mapping {
        if to.len() > 3 {
            return Err(format!("{name}: U+{code:04X} maps to more than 3 code points"));
        }
        if to.len() > 1 {
            expansions.push((code, to));
            continue;
        }
        let delta = i64::from(to[0]) - i64::from(code);
        if let Some(range) = ranges.last_mut() {
            let (first, last, range_delta, stride) = *range;
            let step = code - last;
            let extends = delta == range_delta
                && if first == last { step <= 2 } else { step == stride };
            if extends {
                *range = (first, code, delta, step);
                continue;
            }
        }
        ranges.push((code, code, delta, 1));
    }

    text.push_str(&format!("\nexport let {name}Ranges: Array<Int64> = [\n"));
    for (first, last, delta, stride) in &ranges {
        text.push_str(&format!("    0x{first:04X}, 0x{last:04X}, {delta}, {stride},\n"));
    }
    text.push_str("]\n");
    text.push_str(&format!("\nexport let {name}Expansions: Array<Int64> = [\n"));
    for (code, to) in &expansions {
        let mut slots = [0u32; 3];
        slots[..to.len()].copy_from_slice(to);
        text.push_str(&format!(
            "    0x{code:04X}, 0x{:04X}, 0x{:04X}, 0x{:04X},\n",
            slots[0], slots[1], slots[2]
        ));
    }
    text.push_str("]\n");
    Ok((ranges.len(), expansions.len()))
}

/// `std/normalize-data.thx`: the tables behind `std/normalize` (D226), from
/// UnicodeData (decomposition mappings, canonical combining classes) and
/// DerivedNormalizationProps (Full_Composition_Exclusion). Hangul syllables
/// decompose and compose by formula, so they are not here.
pub fn generate_normalization(ucd: &Path, out: &Path) -> Result<String, String> {
    let read = |name: &str| {
        fs::read_to_string(ucd.join(name)).map_err(|error| format!("{name}: {error}"))
    };
    let unicode_data = read("UnicodeData.txt")?;
    let properties = read("DerivedNormalizationProps.txt")?;
    let version = properties
        .lines()
        .next()
        .and_then(|line| line.strip_prefix("# DerivedNormalizationProps-"))
        .and_then(|rest| rest.strip_suffix(".txt"))
        .ok_or("DerivedNormalizationProps.txt: no version on its first line")?
        .to_string();

    let mut classes: BTreeMap<u32, u32> = BTreeMap::new();
    let mut canonical: Mapping = Mapping::new();
    let mut compatibility: Mapping = Mapping::new();
    for line in unicode_data.lines() {
        let fields: Vec<&str> = line.split(';').collect();
        if fields.len() < 6 {
            continue;
        }
        let code = parse_code(fields[0])?;
        let class: u32 = fields[3].parse().map_err(|_| format!("bad class on {line}"))?;
        if class != 0 {
            classes.insert(code, class);
        }
        let mapping = fields[5].trim();
        if mapping.is_empty() {
            continue;
        }
        match mapping.strip_prefix('<') {
            Some(tagged) => {
                let (_, codes) = tagged.split_once('>').ok_or(format!("bad mapping on {line}"))?;
                compatibility.insert(code, parse_codes(codes)?);
            }
            None => {
                canonical.insert(code, parse_codes(mapping)?);
            }
        }
    }
    let excluded: Vec<(u32, u32)> = property_ranges(&properties, "Full_Composition_Exclusion")?;
    let is_excluded = |code: u32| excluded.iter().any(|&(first, last)| code >= first && code <= last);

    // Full decompositions: mappings applied until nothing maps.
    fn expand(code: u32, canonical: &Mapping, compatibility: Option<&Mapping>, out: &mut Vec<u32>) {
        let mapped = compatibility
            .and_then(|table| table.get(&code))
            .or_else(|| canonical.get(&code));
        match mapped {
            Some(codes) => {
                for &next in codes {
                    expand(next, canonical, compatibility, out);
                }
            }
            None => out.push(code),
        }
    }
    let mut canonical_full: BTreeMap<u32, Vec<u32>> = BTreeMap::new();
    for &code in canonical.keys() {
        let mut out = Vec::new();
        expand(code, &canonical, None, &mut out);
        canonical_full.insert(code, out);
    }
    let mut compatibility_full: BTreeMap<u32, Vec<u32>> = BTreeMap::new();
    for &code in canonical.keys().chain(compatibility.keys()) {
        let mut out = Vec::new();
        expand(code, &canonical, Some(&compatibility), &mut out);
        if canonical_full.get(&code) != Some(&out) {
            compatibility_full.insert(code, out);
        }
    }
    // Primary composites: canonical pairs not excluded from composition.
    let mut compositions: Vec<(u32, u32, u32)> = canonical
        .iter()
        .filter(|(code, codes)| codes.len() == 2 && !is_excluded(**code))
        .map(|(&code, codes)| (codes[0], codes[1], code))
        .collect();
    compositions.sort_unstable();

    let mut text = format!(
        "## Generated by `cargo make unicode <ucd-dir>` from the Unicode {version}\n\
         ## Character Database (UnicodeData, DerivedNormalizationProps). Do not edit.\n\
         ##\n\
         ## Tables for std/normalize (D226), sorted by their first number:\n\
         ## - combiningClasses: first, last, class (classes other than 0);\n\
         ## - canonicalIndex / compatibilityIndex: code point, start, count of its\n\
         ##   full decomposition in the matching pool (compatibility lists only\n\
         ##   the code points whose compatibility decomposition differs);\n\
         ## - compositions: first, second, composite (primary composites).\n\
         ## Hangul syllables decompose and compose by formula.\n\
         \n\
         export let normalizationVersion = \"{version}\"\n"
    );
    let mut class_ranges: Vec<(u32, u32, u32)> = Vec::new();
    for (&code, &class) in &classes {
        match class_ranges.last_mut() {
            Some(range) if range.1 + 1 == code && range.2 == class => range.1 = code,
            _ => class_ranges.push((code, code, class)),
        }
    }
    text.push_str("\nexport let combiningClasses: Array<Int64> = [\n");
    for (first, last, class) in &class_ranges {
        text.push_str(&format!("    0x{first:04X}, 0x{last:04X}, {class},\n"));
    }
    text.push_str("]\n");
    let mut sizes = Vec::new();
    for (name, table) in [("canonical", &canonical_full), ("compatibility", &compatibility_full)] {
        let mut pool: Vec<u32> = Vec::new();
        text.push_str(&format!("\nexport let {name}Index: Array<Int64> = [\n"));
        for (code, codes) in table {
            text.push_str(&format!("    0x{code:04X}, {}, {},\n", pool.len(), codes.len()));
            pool.extend(codes);
        }
        text.push_str("]\n");
        text.push_str(&format!("\nexport let {name}Pool: Array<Int64> = [\n"));
        for chunk in pool.chunks(8) {
            let line: Vec<String> = chunk.iter().map(|code| format!("0x{code:04X}")).collect();
            text.push_str(&format!("    {},\n", line.join(", ")));
        }
        text.push_str("]\n");
        sizes.push(format!("{name} {} entries / {} pool", table.len(), pool.len()));
    }
    text.push_str("\nexport let compositions: Array<Int64> = [\n");
    for (first, second, composite) in &compositions {
        text.push_str(&format!("    0x{first:04X}, 0x{second:04X}, 0x{composite:04X},\n"));
    }
    text.push_str("]\n");
    fs::write(out, text).map_err(|error| format!("{}: {error}", out.display()))?;
    Ok(format!(
        "Unicode {version}: {} class ranges; {}; {} compositions",
        class_ranges.len(),
        sizes.join("; "),
        compositions.len()
    ))
}
