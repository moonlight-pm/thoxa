//! `cargo make unicode <ucd-dir>`: generate `std/unicode.thx`, the case
//! tables behind `String.toLower` / `toUpper` / `ignoreCase:` (D195), which
//! std/string reads (D196).
//!
//! Reads `UnicodeData.txt`, `SpecialCasing.txt`, and `CaseFolding.txt` from a
//! Unicode Character Database directory (https://www.unicode.org/Public/<ver>/ucd/).
//! Each mapping is a table of code points to one or more code points:
//!
//! - lower / upper: UnicodeData's simple mappings, overridden by
//!   SpecialCasing's unconditional ones (`ß` → `SS`); conditional entries
//!   (final sigma, Turkish, Lithuanian) are left out.
//! - fold: CaseFolding's full folding, statuses C and F (`ß` → `ss`).
//!
//! One-to-one mappings are stored as ranges (`first..=last` every `stride`
//! code points maps by `delta`), the rest as a short list of expansions; each
//! is a flat `Array<Int64>` of four numbers per entry.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

type Mapping = BTreeMap<u32, Vec<u32>>;

pub fn generate(ucd: &Path, out: &Path) -> Result<String, String> {
    let read = |name: &str| {
        fs::read_to_string(ucd.join(name)).map_err(|error| format!("{name}: {error}"))
    };
    let unicode_data = read("UnicodeData.txt")?;
    let special_casing = read("SpecialCasing.txt")?;
    let case_folding = read("CaseFolding.txt")?;

    let version = case_folding
        .lines()
        .next()
        .and_then(|line| line.strip_prefix("# CaseFolding-"))
        .and_then(|rest| rest.strip_suffix(".txt"))
        .ok_or("CaseFolding.txt: no version on its first line")?
        .to_string();

    let mut lower = Mapping::new();
    let mut upper = Mapping::new();
    for line in unicode_data.lines() {
        let fields: Vec<&str> = line.split(';').collect();
        if fields.len() < 15 {
            continue;
        }
        let code = parse_code(fields[0])?;
        if !fields[12].is_empty() {
            upper.insert(code, vec![parse_code(fields[12])?]);
        }
        if !fields[13].is_empty() {
            lower.insert(code, vec![parse_code(fields[13])?]);
        }
    }

    for line in special_casing.lines() {
        let data = line.split('#').next().unwrap_or("").trim();
        if data.is_empty() {
            continue;
        }
        let fields: Vec<&str> = data.split(';').map(str::trim).collect();
        // code; lower; title; upper; [conditions;]
        if fields.len() > 4 && !fields[4].is_empty() {
            continue;
        }
        let code = parse_code(fields[0])?;
        override_mapping(&mut lower, code, parse_codes(fields[1])?);
        override_mapping(&mut upper, code, parse_codes(fields[3])?);
    }

    let mut fold = Mapping::new();
    for line in case_folding.lines() {
        let data = line.split('#').next().unwrap_or("").trim();
        if data.is_empty() {
            continue;
        }
        let fields: Vec<&str> = data.split(';').map(str::trim).collect();
        if fields.len() < 3 || !matches!(fields[1], "C" | "F") {
            continue;
        }
        fold.insert(parse_code(fields[0])?, parse_codes(fields[2])?);
    }

    let mut text = format!(
        "## Generated by `cargo make unicode <ucd-dir>` from the Unicode {version}\n\
         ## Character Database (UnicodeData, SpecialCasing, CaseFolding). Do not edit.\n\
         ##\n\
         ## Case tables for String's methods in std/string (D195, D196). A range is\n\
         ## four numbers: first, last, delta, stride; the code points from first to\n\
         ## last, every stride, map to themselves plus delta. An expansion is four\n\
         ## numbers: a code point, then the up to three it maps to (0 when unused).\n\
         ## Both are sorted by their first number.\n\
         \n\
         export let unicodeVersion = \"{version}\"\n"
    );
    let mut summary = format!("Unicode {version}:");
    for (name, mapping) in [("lower", &lower), ("upper", &upper), ("fold", &fold)] {
        let (ranges, expansions) = emit_table(&mut text, name, mapping)?;
        summary.push_str(&format!(" {name} {ranges} ranges + {expansions} expansions;"));
    }
    fs::write(out, text).map_err(|error| format!("{}: {error}", out.display()))?;
    Ok(summary)
}

fn parse_code(text: &str) -> Result<u32, String> {
    u32::from_str_radix(text.trim(), 16).map_err(|_| format!("bad code point `{text}`"))
}

fn parse_codes(text: &str) -> Result<Vec<u32>, String> {
    text.split_whitespace().map(parse_code).collect()
}

/// A SpecialCasing entry replaces the simple mapping; mapping to itself
/// removes it.
fn override_mapping(mapping: &mut Mapping, code: u32, to: Vec<u32>) {
    if to == [code] {
        mapping.remove(&code);
    } else {
        mapping.insert(code, to);
    }
}

fn emit_table(text: &mut String, name: &str, mapping: &Mapping) -> Result<(usize, usize), String> {
    let mut ranges: Vec<(u32, u32, i64, u32)> = Vec::new();
    let mut expansions: Vec<(u32, &[u32])> = Vec::new();
    for (&code, to) in mapping {
        if to.len() > 3 {
            return Err(format!("{name}: U+{code:04X} maps to more than 3 code points"));
        }
        if to.len() > 1 {
            expansions.push((code, to));
            continue;
        }
        let delta = i64::from(to[0]) - i64::from(code);
        if let Some(range) = ranges.last_mut() {
            let (first, last, range_delta, stride) = *range;
            let step = code - last;
            let extends = delta == range_delta
                && if first == last { step <= 2 } else { step == stride };
            if extends {
                *range = (first, code, delta, step);
                continue;
            }
        }
        ranges.push((code, code, delta, 1));
    }

    text.push_str(&format!("\nexport let {name}Ranges: Array<Int64> = [\n"));
    for (first, last, delta, stride) in &ranges {
        text.push_str(&format!("    0x{first:04X}, 0x{last:04X}, {delta}, {stride},\n"));
    }
    text.push_str("]\n");
    text.push_str(&format!("\nexport let {name}Expansions: Array<Int64> = [\n"));
    for (code, to) in &expansions {
        let mut slots = [0u32; 3];
        slots[..to.len()].copy_from_slice(to);
        text.push_str(&format!(
            "    0x{code:04X}, 0x{:04X}, 0x{:04X}, 0x{:04X},\n",
            slots[0], slots[1], slots[2]
        ));
    }
    text.push_str("]\n");
    Ok((ranges.len(), expansions.len()))
}
