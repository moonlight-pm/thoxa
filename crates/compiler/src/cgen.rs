fn emit_map_get(
    out: &mut String,
    pad: &str,
    found: &crate::mir::Place,
    map: &crate::mir::Place,
    key: &crate::mir::Place,
    dest: &crate::mir::Place,
    val_ty: &Ty,
    types: &[TypeLayout],
) {
    match val_ty {
        Ty::User(_) if is_boxed_user(val_ty, types) => {
            let _ = writeln!(
                out,
                "{pad}{} = thoxa_map_get_ptr({}, {}, (void **)&{});",
                found.name,
                map.name,
                c_map_key_bits(&key.name),
                dest.name
            );
        }
        Ty::User(_) => {
            // Borrow the slot (memcpy, no elem_dup). MIR then Dups `needs_drop`
            // values the same way as MapGet of String/Array/Map (Has + result).
            // elem_dup here plus those Dups freed the value while the map still
            // held it — nested Type.read after another read then heap-corrupted.
            let _ = writeln!(
                out,
                "{pad}{} = thoxa_map_get_elem({}, {}, &{}, NULL);",
                found.name,
                map.name,
                c_map_key_bits(&key.name),
                dest.name
            );
        }
        Ty::String | Ty::Bytes | Ty::Node | Ty::Array { .. } | Ty::Map { .. } => {
            let _ = writeln!(
                out,
                "{pad}{} = thoxa_map_get_ptr({}, {}, (void **)&{});",
                found.name,
                map.name,
                c_map_key_bits(&key.name),
                dest.name
            );
        }
        Ty::Bool => {
            let tmp = format!("{}_i", dest.name);
            let _ = writeln!(out, "{pad}int64_t {tmp} = 0;");
            let _ = writeln!(
                out,
                "{pad}{} = thoxa_map_get_i64({}, {}, &{tmp});",
                found.name,
                map.name,
                c_map_key_bits(&key.name)
            );
            let _ = writeln!(out, "{pad}{} = {tmp} != 0;", dest.name);
        }
        Ty::Float64 => {
            let tmp = format!("{}_i", dest.name);
            let _ = writeln!(out, "{pad}int64_t {tmp} = 0;");
            let _ = writeln!(
                out,
                "{pad}{} = thoxa_map_get_i64({}, {}, &{tmp});",
                found.name,
                map.name,
                c_map_key_bits(&key.name)
            );
            let _ = writeln!(
                out,
                "{pad}{} = thoxa_f64_from_bits((uint64_t){tmp});",
                dest.name
            );
        }
        _ => {
            let _ = writeln!(
                out,
                "{pad}{} = thoxa_map_get_i64({}, {}, &{});",
                found.name,
                map.name,
                c_map_key_bits(&key.name),
                dest.name
            );
        }
    }
}

