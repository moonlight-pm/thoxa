//! MIR → C source.

use crate::ast::{BinaryOp, UnaryOp};
use crate::mir::{Callee, Function, GlobalVar, Program, RValue, Stmt, TrialTag, Ty, TypeLayout};
use std::collections::HashSet;
use std::fmt::Write as _;

pub fn emit_program(program: &Program) -> String {
    let mut out = String::new();
    out.push_str("/* Generated by thoxa — do not edit */\n");
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include <stdbool.h>\n");
    out.push_str("#include <stddef.h>\n");
    // R6–R9+: libc (`extern fn … from "c"`). sockets for Net; fcntl for open(2); string.h.
    if !program.externs.is_empty() {
        out.push_str("#include <stdlib.h>\n");
        out.push_str("#include <string.h>\n");
        out.push_str("#include <unistd.h>\n");
        out.push_str("#include <fcntl.h>\n");
        out.push_str("#include <sys/socket.h>\n");
        out.push_str("#include <netinet/in.h>\n");
    }
    out.push_str("#include \"thoxa_rt.h\"\n\n");
    let _ = program.externs; // used for include selection above

    // User structs first (may appear as Trial ok payloads / Array elements).
    for t in &program.types {
        emit_typedef(&mut out, t);
    }

    // Monomorphized Trial typedefs used by this program.
    let mut trial_tys: Vec<Ty> = Vec::new();
    collect_trial_tys_program(program, &mut trial_tys);
    for ty in &trial_tys {
        emit_trial_typedef(&mut out, ty);
    }
    if !trial_tys.is_empty() {
        out.push('\n');
    }

    // Per-User-type field RC helpers for Array<User> (D65).
    let mut user_arr_elems: Vec<String> = Vec::new();
    collect_user_array_elems_program(program, &mut user_arr_elems);
    for name in &user_arr_elems {
        if let Some(layout) = program.types.iter().find(|t| t.name == *name) {
            emit_array_user_elem_rc(&mut out, layout);
        }
    }
    if !user_arr_elems.is_empty() {
        out.push('\n');
    }

    // Module-level statics (R8).
    for g in &program.globals {
        emit_global(&mut out, g);
    }
    if !program.globals.is_empty() {
        out.push('\n');
    }

    for f in &program.functions {
        emit_proto(&mut out, f);
    }
    out.push('\n');

    // Module initializer (top-level let/mut values).
    if !program.init.is_empty() {
        out.push_str("static void thoxa_module_init(void) {\n");
        // Temps used by init stmts need locals.
        let mut locals: Vec<(String, Ty)> = Vec::new();
        let mut seen = HashSet::new();
        collect_locals(&program.init, &mut locals, &mut seen);
        // Don't redeclare globals as locals.
        let global_names: HashSet<&str> = program.globals.iter().map(|g| g.name.as_str()).collect();
        for (name, ty) in &locals {
            if global_names.contains(name.as_str()) {
                continue;
            }
            if *ty == Ty::Void {
                continue;
            }
            emit_local_decl(&mut out, name, ty);
        }
        emit_stmts(&mut out, &program.init, 1, &program.types);
        out.push_str("}\n\n");
    }

    let global_names: HashSet<String> = program.globals.iter().map(|g| g.name.clone()).collect();
    let type_layouts = &program.types;

    for f in &program.functions {
        emit_function(&mut out, f, &global_names, type_layouts);
        out.push('\n');
    }

    out.push_str("int main(void) {\n");
    if !program.init.is_empty() {
        out.push_str("    thoxa_module_init();\n");
    }
    out.push_str("    return (int)thoxa_fn_main();\n");
    out.push_str("}\n");
    out
}

fn emit_global(out: &mut String, g: &GlobalVar) {
    if is_heap_ty(&g.ty) {
        let _ = writeln!(out, "static {} {} = NULL;", c_ty(&g.ty), g.name);
    } else {
        let _ = writeln!(out, "static {} {};", c_ty(&g.ty), g.name);
    }
}

fn emit_typedef(out: &mut String, t: &TypeLayout) {
    let _ = writeln!(out, "typedef struct {{");
    for f in &t.fields {
        match &f.ty {
            Ty::FixedArray { elem, len } => {
                let _ = writeln!(out, "    {} {}[{len}];", c_ty(elem), f.c_name);
            }
            other => {
                let _ = writeln!(out, "    {} {};", c_ty(other), f.c_name);
            }
        }
    }
    if t.fields.is_empty() {
        out.push_str("    char _pad;\n");
    }
    let _ = writeln!(out, "}} {};\n", c_type_name(&t.name));
}

fn emit_proto(out: &mut String, f: &Function) {
    let c_name = c_fn_name(f);
    let ret = c_ty(&f.ret_ty);
    let _ = write!(out, "{ret} {c_name}(");
    emit_params(out, f);
    out.push_str(");\n");
}

fn emit_params(out: &mut String, f: &Function) {
    let mut first = true;
    if let Some((name, ty)) = &f.receiver {
        let _ = write!(out, "{} {}", c_ty(ty), name);
        first = false;
    }
    if f.params.is_empty() && f.receiver.is_none() {
        out.push_str("void");
        return;
    }
    for (name, ty) in &f.params {
        if !first {
            out.push_str(", ");
        }
        first = false;
        let _ = write!(out, "{} {}", c_ty(ty), name);
    }
}

fn emit_function(
    out: &mut String,
    f: &Function,
    global_names: &HashSet<String>,
    types: &[TypeLayout],
) {
    let c_name = c_fn_name(f);
    let ret = c_ty(&f.ret_ty);
    let _ = write!(out, "{ret} {c_name}(");
    emit_params(out, f);
    out.push_str(") {\n");

    let mut locals: Vec<(String, Ty)> = Vec::new();
    let mut seen = HashSet::new();
    if let Some((name, _)) = &f.receiver {
        seen.insert(name.clone());
    }
    for (name, _) in &f.params {
        seen.insert(name.clone());
    }
    // Module-level statics are already declared; never redeclare as locals.
    for g in global_names {
        seen.insert(g.clone());
    }
    collect_locals(&f.body, &mut locals, &mut seen);
    if let Some(ref r) = f.ret {
        if seen.insert(r.name.clone()) {
            locals.push((r.name.clone(), f.ret_ty.clone()));
        }
    }

    for (name, ty) in &locals {
        if *ty == Ty::Void {
            continue;
        }
        emit_local_decl(out, name, ty);
    }

    emit_stmts(out, &f.body, 1, types);

    match (&f.ret, &f.ret_ty) {
        (Some(_), Ty::Void) => {}
        (Some(p), _) => {
            let _ = writeln!(out, "    return {};", p.name);
        }
        (None, Ty::Void) => {}
        (None, _) => {
            out.push_str("    return 0;\n");
        }
    }
    out.push_str("}\n");
}

fn is_heap_ty(ty: &Ty) -> bool {
    matches!(ty, Ty::String | Ty::Bytes | Ty::Buffer | Ty::Array { .. })
}

/// Same policy as MIR `needs_drop` — User always walks fields (may be no-op).
fn needs_drop_ty(ty: &Ty) -> bool {
    match ty {
        Ty::String | Ty::Bytes | Ty::Buffer | Ty::Array { .. } | Ty::User(_) => true,
        Ty::Trial { ok, err } => needs_drop_ty(ok) || needs_drop_ty(err),
        _ => false,
    }
}

/// Declare a local with a safe zero value (so branch-skipped drops are no-ops).
fn emit_local_decl(out: &mut String, name: &str, ty: &Ty) {
    match ty {
        Ty::String | Ty::Bytes | Ty::Buffer | Ty::Array { .. } => {
            let _ = writeln!(out, "    {} {} = NULL;", c_ty(ty), name);
        }
        Ty::User(_) => {
            // Zero so field drops of unassigned / branch-skipped locals are safe (NULL heap ptrs).
            let _ = writeln!(out, "    {} {} = {{0}};", c_ty(ty), name);
        }
        Ty::Trial { ok, err } => {
            // tag=0 (Pass), heap sides NULL, scalars 0 — drop is a no-op until assigned.
            let _ = write!(out, "    {} {} = {{ .tag = 0", c_ty(ty), name);
            if *ok.as_ref() != Ty::Void {
                if is_heap_ty(ok) {
                    out.push_str(", .ok = NULL");
                } else if matches!(ok.as_ref(), Ty::Bool) {
                    out.push_str(", .ok = false");
                } else if matches!(ok.as_ref(), Ty::User(_)) {
                    let _ = write!(out, ", .ok = ({}){{0}}", c_ty(ok));
                } else {
                    out.push_str(", .ok = 0");
                }
            }
            if *err.as_ref() != Ty::Void {
                if is_heap_ty(err) {
                    out.push_str(", .err = NULL");
                } else if matches!(err.as_ref(), Ty::Bool) {
                    out.push_str(", .err = false");
                } else if matches!(err.as_ref(), Ty::User(_)) {
                    let _ = write!(out, ", .err = ({}){{0}}", c_ty(err));
                } else {
                    out.push_str(", .err = 0");
                }
            }
            out.push_str(" };\n");
        }
        _ => {
            let _ = writeln!(out, "    {} {};", c_ty(ty), name);
        }
    }
}

fn collect_locals(stmts: &[Stmt], locals: &mut Vec<(String, Ty)>, seen: &mut HashSet<String>) {
    for s in stmts {
        match s {
            Stmt::Assign { place, ty, .. } => {
                if seen.insert(place.name.clone()) {
                    locals.push((place.name.clone(), ty.clone()));
                }
            }
            Stmt::FieldAssign { .. }
            | Stmt::IndexAssign { .. }
            | Stmt::DynIndexAssign { .. }
            | Stmt::Eval(_) => {}
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_locals(then_body, locals, seen);
                collect_locals(else_body, locals, seen);
            }
            Stmt::Loop { body } => collect_locals(body, locals, seen),
            Stmt::ForRange { body, .. } => collect_locals(body, locals, seen),
            Stmt::Return { .. }
            | Stmt::Dup { .. }
            | Stmt::Drop { .. }
            | Stmt::Break
            | Stmt::Continue => {}
        }
    }
}

// Note: FieldAssign/IndexAssign do not introduce new locals.

fn emit_stmts(out: &mut String, stmts: &[Stmt], indent: usize, types: &[TypeLayout]) {
    let pad = "    ".repeat(indent);
    for s in stmts {
        match s {
            Stmt::Assign { place, value, .. } => {
                // User ArrayGet writes through out-param (not an expression).
                if let RValue::ArrayGet {
                    arr,
                    index,
                    elem_ty: Ty::User(type_name),
                } = value
                {
                    let _ = writeln!(
                        out,
                        "{pad}thoxa_array_get_elem({}, {}, &{}, {});",
                        arr.name,
                        index.name,
                        place.name,
                        array_user_elem_dup_fn(type_name)
                    );
                } else {
                    let _ = write!(out, "{pad}{} = ", place.name);
                    emit_rvalue(out, value, types);
                    out.push_str(";\n");
                }
            }
            Stmt::FieldAssign {
                base,
                field,
                ty,
                value,
            } => {
                let _ = writeln!(
                    out,
                    "{pad}{}.{} = ({}){};",
                    base.name,
                    field,
                    c_ty(ty),
                    value.name
                );
            }
            Stmt::IndexAssign {
                base,
                field,
                index,
                ty,
                value,
            } => {
                let _ = writeln!(
                    out,
                    "{pad}{}.{}[{}] = ({}){};",
                    base.name,
                    field,
                    index.name,
                    c_ty(ty),
                    value.name
                );
            }
            Stmt::DynIndexAssign {
                base,
                index,
                elem_ty,
                value,
            } => match elem_ty {
                Ty::String | Ty::Bytes => {
                    let _ = writeln!(
                        out,
                        "{pad}thoxa_array_set_ptr({}, {}, {});",
                        base.name, index.name, value.name
                    );
                }
                Ty::Bool => {
                    let _ = writeln!(
                        out,
                        "{pad}thoxa_array_set_i64({}, {}, {} ? INT64_C(1) : INT64_C(0));",
                        base.name, index.name, value.name
                    );
                }
                Ty::User(type_name) => {
                    let _ = writeln!(
                        out,
                        "{pad}thoxa_array_set_elem({}, {}, &{}, {}, {});",
                        base.name,
                        index.name,
                        value.name,
                        array_user_elem_dup_fn(type_name),
                        array_user_elem_drop_fn(type_name)
                    );
                }
                _ => {
                    let _ = writeln!(
                        out,
                        "{pad}thoxa_array_set_i64({}, {}, (int64_t){});",
                        base.name, index.name, value.name
                    );
                }
            },
            Stmt::Eval(rv) => {
                let _ = write!(out, "{pad}");
                emit_rvalue(out, rv, types);
                out.push_str(";\n");
            }
            Stmt::If {
                cond,
                then_body,
                else_body,
            } => {
                let _ = writeln!(out, "{pad}if ({}) {{", cond.name);
                emit_stmts(out, then_body, indent + 1, types);
                if else_body.is_empty() {
                    let _ = writeln!(out, "{pad}}}");
                } else {
                    let _ = writeln!(out, "{pad}}} else {{");
                    emit_stmts(out, else_body, indent + 1, types);
                    let _ = writeln!(out, "{pad}}}");
                }
            }
            Stmt::Loop { body } => {
                let _ = writeln!(out, "{pad}while (1) {{");
                emit_stmts(out, body, indent + 1, types);
                let _ = writeln!(out, "{pad}}}");
            }
            Stmt::ForRange {
                index,
                end,
                inclusive,
                body,
            } => {
                let cmp = if *inclusive { "<=" } else { "<" };
                // Index already initialized to the range start before this stmt.
                let _ = writeln!(
                    out,
                    "{pad}for (; {} {} {}; {} = {} + INT64_C(1)) {{",
                    index.name, cmp, end.name, index.name, index.name
                );
                emit_stmts(out, body, indent + 1, types);
                let _ = writeln!(out, "{pad}}}");
            }
            Stmt::Break => {
                let _ = writeln!(out, "{pad}break;");
            }
            Stmt::Continue => {
                let _ = writeln!(out, "{pad}continue;");
            }
            Stmt::Return { value } => match value {
                Some(p) => {
                    let _ = writeln!(out, "{pad}return {};", p.name);
                }
                None => {
                    let _ = writeln!(out, "{pad}return;");
                }
            },
            Stmt::Dup { place, ty } => {
                emit_rc(out, &pad, place, ty, true, types);
            }
            Stmt::Drop { place, ty } => {
                emit_rc(out, &pad, place, ty, false, types);
            }
        }
    }
}

fn emit_rvalue(out: &mut String, rv: &RValue, types: &[TypeLayout]) {
    let _ = types;
    match rv {
        RValue::Use(p) => {
            out.push_str(&p.name);
        }
        RValue::Int(n) => {
            let _ = write!(out, "INT64_C({n})");
        }
        RValue::Bool(b) => {
            out.push_str(if *b { "true" } else { "false" });
        }
        RValue::StringLit(s) => {
            out.push_str("thoxa_string_from_cstr(");
            emit_c_string(out, s);
            out.push(')');
        }
        RValue::Null => {
            out.push_str("NULL");
        }
        RValue::Unary { op, arg } => match op {
            UnaryOp::Neg => {
                let _ = write!(out, "-({})", arg.name);
            }
            UnaryOp::Not => {
                let _ = write!(out, "!({})", arg.name);
            }
            UnaryOp::BitNot => {
                let _ = write!(out, "~({})", arg.name);
            }
        },
        RValue::Binary { op, left, right } => {
            let opc = match op {
                BinaryOp::Add => "+",
                BinaryOp::Sub => "-",
                BinaryOp::Mul => "*",
                BinaryOp::Div => "/",
                BinaryOp::Rem => "%",
                BinaryOp::Eq => "==",
                BinaryOp::Ne => "!=",
                BinaryOp::Lt => "<",
                BinaryOp::Le => "<=",
                BinaryOp::Gt => ">",
                BinaryOp::Ge => ">=",
                BinaryOp::And => "&&",
                BinaryOp::Or => "||",
                BinaryOp::BitAnd => "&",
                BinaryOp::BitOr => "|",
                BinaryOp::BitXor => "^",
                BinaryOp::Shl => "<<",
                BinaryOp::Shr => ">>",
            };
            let _ = write!(out, "({}) {} ({})", left.name, opc, right.name);
        }
        RValue::Call { callee, args } => match callee {
            Callee::Builtin(name) => {
                let c = match name.as_str() {
                    "println" => "thoxa_println",
                    "print" => "thoxa_print",
                    "println_string" => "thoxa_println_string",
                    "print_string" => "thoxa_print_string",
                    "println_i64" => "thoxa_println_i64",
                    "print_i64" => "thoxa_print_i64",
                    "println_bool" => "thoxa_println_bool",
                    "print_bool" => "thoxa_print_bool",
                    "string_eq" => "thoxa_string_eq",
                    "bytes_from_string" => "thoxa_bytes_from_string",
                    "bytes_new" => "thoxa_bytes_new",
                    "bytes_count" => "(int64_t)thoxa_bytes_count",
                    "bytes_get" => "thoxa_bytes_get",
                    "bytes_set" => "thoxa_bytes_set",
                    "bytes_slice" => "thoxa_bytes_slice",
                    "bytes_find" => "thoxa_bytes_find",
                    "bytes_to_string" => "thoxa_bytes_to_string",
                    "buffer_new" => "thoxa_buffer_new",
                    "buffer_with_capacity" => "thoxa_buffer_with_capacity",
                    "buffer_count" => "thoxa_buffer_count",
                    "buffer_capacity" => "thoxa_buffer_capacity",
                    "buffer_append" => "thoxa_buffer_append",
                    "buffer_append_bytes" => "thoxa_buffer_append_bytes",
                    "buffer_freeze" => "thoxa_buffer_freeze",
                    "array_count" => "thoxa_array_count",
                    "array_get_i64" => "thoxa_array_get_i64",
                    "array_get_ptr" => "thoxa_array_get_ptr",
                    "array_append_i64" => "thoxa_array_append_i64",
                    "array_append_ptr" => "thoxa_array_append_ptr",
                    "array_drop_last" => "thoxa_array_drop_last",
                    other => other,
                };
                out.push_str(c);
                out.push('(');
                for (i, a) in args.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    out.push_str(&a.name);
                }
                out.push(')');
            }
            Callee::User(name) => {
                out.push_str(&c_free_fn_name(name));
                out.push('(');
                for (i, a) in args.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    out.push_str(&a.name);
                }
                out.push(')');
            }
            Callee::Method { type_name, method } => {
                let _ = write!(out, "{}", c_method_name(type_name, method));
                out.push('(');
                for (i, a) in args.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    out.push_str(&a.name);
                }
                out.push(')');
            }
            Callee::Extern { c_symbol, arg_tys } => {
                let _ = write!(out, "{c_symbol}(");
                for (i, a) in args.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    let ty = arg_tys.get(i);
                    match ty {
                        Some(Ty::String) => {
                            let _ = write!(out, "thoxa_string_cstr({})", a.name);
                        }
                        Some(Ty::Bytes) => {
                            let _ = write!(out, "(void *)thoxa_bytes_data({})", a.name);
                        }
                        Some(Ty::Address(_)) => {
                            // Implicit address-of for mut struct bindings.
                            let _ = write!(out, "&{}", a.name);
                        }
                        _ => out.push_str(&a.name),
                    }
                }
                out.push(')');
            }
        },
        RValue::TrialMake {
            tag,
            payload,
            trial_ty,
        } => {
            emit_trial_make(out, tag, payload, trial_ty);
        }
        RValue::TrialTag(p) => {
            let _ = write!(out, "(int64_t)({}.tag)", p.name);
        }
        RValue::TrialOk(p) => {
            let _ = write!(out, "{}.ok", p.name);
        }
        RValue::TrialErr(p) => {
            let _ = write!(out, "{}.err", p.name);
        }
        RValue::StructLit { type_name, fields } => {
            let _ = write!(out, "({}){{", c_type_name(type_name));
            for (i, f) in fields.iter().enumerate() {
                if i > 0 {
                    out.push_str(", ");
                }
                out.push_str(&f.name);
            }
            out.push('}');
        }
        RValue::StructZero { type_name } => {
            // C compound literal: all fields (and padding) zero-initialized.
            let _ = write!(out, "({}){{0}}", c_type_name(type_name));
        }
        RValue::Field { base, field } => {
            let _ = write!(out, "{}.{}", base.name, field);
        }
        RValue::Index { base, field, index } => {
            let _ = write!(out, "{}.{}[{}]", base.name, field, index.name);
        }
        RValue::ArrayLit { elems, elem_ty } => {
            emit_array_lit(out, elems, elem_ty);
        }
        RValue::ArrayGet { .. } => {
            // Handled specially in Stmt::Assign (out-param).
            out.push_str("/* bad ArrayGet as rvalue */");
        }
        RValue::ArrayAppend { arr, item, elem_ty } => match elem_ty {
            Ty::User(type_name) => {
                let _ = write!(
                    out,
                    "thoxa_array_append_elem({}, &{}, (uint32_t)sizeof({}), 0u, {})",
                    arr.name,
                    item.name,
                    c_type_name(type_name),
                    array_user_elem_dup_fn(type_name)
                );
            }
            _ => {
                out.push_str("/* bad ArrayAppend elem */ NULL");
            }
        },
        RValue::ArrayDropLast { arr, elem_ty } => match elem_ty {
            Ty::User(type_name) => {
                let _ = write!(
                    out,
                    "thoxa_array_drop_last_ex({}, {})",
                    arr.name,
                    array_user_elem_dup_fn(type_name)
                );
            }
            _ => {
                let _ = write!(out, "thoxa_array_drop_last({})", arr.name);
            }
        },
        RValue::ToString { value, from } => match from {
            Ty::Int64 => {
                let _ = write!(out, "thoxa_string_from_i64({})", value.name);
            }
            Ty::Bool => {
                let _ = write!(out, "thoxa_string_from_bool({})", value.name);
            }
            Ty::Array { elem } if matches!(elem.as_ref(), Ty::Int64 | Ty::Bool) => {
                let _ = write!(out, "thoxa_array_i64_to_string({})", value.name);
            }
            Ty::Array { elem } if matches!(elem.as_ref(), Ty::String) => {
                let _ = write!(out, "thoxa_array_string_to_string({})", value.name);
            }
            _ => {
                let _ = write!(out, "/* bad ToString */ NULL");
            }
        },
        RValue::StringConcat { left, right } => {
            let _ = write!(out, "thoxa_string_concat({}, {})", left.name, right.name);
        }
        RValue::Cast { value, from, to } => {
            let _ = write!(out, "({})({})", c_ty(to), value.name);
            let _ = from; // from is for diagnostics; C cast is enough
        }
    }
}

fn emit_c_string(out: &mut String, s: &str) {
    out.push('\"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            '\0' => out.push_str("\\0"),
            c if c.is_control() => {
                let _ = write!(out, "\\x{:02x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('\"');
}

fn c_ty(ty: &Ty) -> String {
    match ty {
        Ty::Int32 => "int32_t".into(),
        Ty::Int64 => "int64_t".into(),
        Ty::UInt32 => "uint32_t".into(),
        Ty::UInt64 => "uint64_t".into(),
        Ty::Byte => "uint8_t".into(),
        Ty::Bool => "bool".into(),
        Ty::String => "ThoxaString*".into(),
        Ty::Bytes => "ThoxaBytes*".into(),
        Ty::Buffer => "ThoxaBuffer*".into(),
        Ty::Array { .. } => "ThoxaArray*".into(),
        Ty::Void => "void".into(),
        Ty::Trial { .. } => trial_c_name(ty),
        Ty::User(name) => c_type_name(name),
        Ty::FixedArray { elem, .. } => {
            // Locals of fixed-array type are not emitted; typedefs handle arrays.
            c_ty(elem)
        }
        Ty::Address(inner) => format!("{}*", c_ty(inner)),
    }
}

fn emit_array_lit(out: &mut String, elems: &[crate::mir::Place], elem_ty: &Ty) {
    let heap = matches!(elem_ty, Ty::String | Ty::Bytes);
    if let Ty::User(type_name) = elem_ty {
        let cty = c_type_name(type_name);
        let dup = array_user_elem_dup_fn(type_name);
        if elems.is_empty() {
            let _ = write!(out, "thoxa_array_new_ex((uint32_t)sizeof({cty}), 0u)");
            return;
        }
        // Compound literal of structs; from_elems shallow-copies then field-dups.
        let _ = write!(out, "thoxa_array_from_elems((const void *)({cty}[]){{");
        for (i, e) in elems.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            out.push_str(&e.name);
        }
        let _ = write!(
            out,
            "}}, {}, (uint32_t)sizeof({cty}), 0u, {dup})",
            elems.len()
        );
        return;
    }
    if elems.is_empty() {
        let _ = write!(out, "thoxa_array_new({})", if heap { 1 } else { 0 });
        return;
    }
    if heap {
        out.push_str("thoxa_array_from_ptrs((void *const[]){");
        for (i, e) in elems.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            let _ = write!(out, "(void *){}", e.name);
        }
        let _ = write!(out, "}}, {})", elems.len());
    } else {
        out.push_str("thoxa_array_from_i64((const int64_t[]){");
        for (i, e) in elems.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            match elem_ty {
                Ty::Bool => {
                    let _ = write!(out, "({} ? INT64_C(1) : INT64_C(0))", e.name);
                }
                _ => {
                    let _ = write!(out, "(int64_t){}", e.name);
                }
            }
        }
        let _ = write!(out, "}}, {})", elems.len());
    }
}

fn trial_c_name(ty: &Ty) -> String {
    match ty {
        Ty::Trial { ok, err } => {
            format!("ThoxaTrial_{}_{}", ty_mangle(ok), ty_mangle(err))
        }
        _ => "ThoxaTrial_Invalid".into(),
    }
}

fn ty_mangle(ty: &Ty) -> String {
    match ty {
        Ty::Void => "Void".into(),
        Ty::Int32 => "I32".into(),
        Ty::Int64 => "I64".into(),
        Ty::UInt32 => "U32".into(),
        Ty::UInt64 => "U64".into(),
        Ty::Byte => "Byte".into(),
        Ty::Bool => "Bool".into(),
        Ty::String => "String".into(),
        Ty::Bytes => "Bytes".into(),
        Ty::Buffer => "Buffer".into(),
        Ty::User(n) => n.replace('-', "_"),
        other => format!("{other:?}").replace(['<', '>', ' ', ','], "_"),
    }
}

fn emit_trial_typedef(out: &mut String, ty: &Ty) {
    let Ty::Trial { ok, err } = ty else {
        return;
    };
    let name = trial_c_name(ty);
    let _ = writeln!(out, "typedef struct {{");
    out.push_str("    int32_t tag; /* 0 = Pass, 1 = Fail */\n");
    if *ok.as_ref() != Ty::Void {
        let _ = writeln!(out, "    {} ok;", c_ty(ok));
    }
    if *err.as_ref() != Ty::Void {
        let _ = writeln!(out, "    {} err;", c_ty(err));
    }
    // C forbids empty structs in some modes; ensure at least tag is present.
    let _ = writeln!(out, "}} {name};");
}

fn emit_trial_make(out: &mut String, tag: &TrialTag, payload: &crate::mir::Place, trial_ty: &Ty) {
    let Ty::Trial { ok, err } = trial_ty else {
        out.push_str("/* bad TrialMake */");
        return;
    };
    let name = trial_c_name(trial_ty);
    match tag {
        TrialTag::Pass => {
            // Compound literal: tag=0, ok=payload (if not Void), err zeroed.
            let _ = write!(out, "({name}){{ .tag = 0");
            if *ok.as_ref() != Ty::Void {
                let _ = write!(out, ", .ok = {}", payload.name);
            }
            if *err.as_ref() != Ty::Void {
                if is_heap_ty(err) {
                    out.push_str(", .err = NULL");
                } else if matches!(err.as_ref(), Ty::Bool) {
                    out.push_str(", .err = false");
                } else if matches!(err.as_ref(), Ty::User(_)) {
                    let _ = write!(out, ", .err = ({}){{0}}", c_ty(err));
                } else {
                    out.push_str(", .err = 0");
                }
            }
            out.push_str(" }");
            // Heap ok payload: extra ref owned by the Trial (temp also dropped).
            // Emitted as statement after assign — see assign path. Dup in MIR for Use;
            // for TrialMake we emit trailing dup via a statement in MIR... handled below in post?
            // We dup in emit by wrapping: ({ ...; thoxa_dup; t; }) — use GNU statement expr, or
            // rely on MIR. Prefer MIR: after TrialMake assign, if heap ok, Dup the trial? No —
            // cgen emits compound literal sharing pointer; MIR should Dup payload after.
            // Actually emit: ( (name){...} ) and if heap, the assign in MIR for Pass already
            // has the payload place still live; we need Dup on the trial's ok field after.
            // Simplest: if ok is heap, compound literal + runtime will share; MIR inserts
            // Dup on payload place before TrialMake so RC is 2, then drop payload → 1 in trial.
            // Wait — Dup on payload before make: RC=2, make shares pointer, drop payload RC=1. OK.
        }
        TrialTag::Fail => {
            let _ = write!(out, "({name}){{ .tag = 1");
            if *ok.as_ref() != Ty::Void {
                if is_heap_ty(ok) {
                    out.push_str(", .ok = NULL");
                } else if matches!(ok.as_ref(), Ty::Bool) {
                    out.push_str(", .ok = false");
                } else if matches!(ok.as_ref(), Ty::User(_)) {
                    let _ = write!(out, ", .ok = ({}){{0}}", c_ty(ok));
                } else {
                    out.push_str(", .ok = 0");
                }
            }
            if *err.as_ref() != Ty::Void {
                let _ = write!(out, ", .err = {}", payload.name);
            }
            out.push_str(" }");
        }
    }
}

fn array_user_elem_dup_fn(type_name: &str) -> String {
    format!("thoxa_arr_elem_dup_{type_name}")
}

fn array_user_elem_drop_fn(type_name: &str) -> String {
    format!("thoxa_arr_elem_drop_{type_name}")
}

/// Static field-walk helpers used as ThoxaArrayElemFn for Array<User>.
fn emit_array_user_elem_rc(out: &mut String, layout: &TypeLayout) {
    let cty = c_type_name(&layout.name);
    let dup = array_user_elem_dup_fn(&layout.name);
    let drop = array_user_elem_drop_fn(&layout.name);
    let _ = writeln!(out, "static void {dup}(void *p) {{");
    let _ = writeln!(out, "    {cty} *e = ({cty} *)p;");
    for f in &layout.fields {
        if !needs_drop_ty(&f.ty) {
            continue;
        }
        // Only String/Bytes fields need thoxa_dup (User array elems are ctor-param).
        match &f.ty {
            Ty::String | Ty::Bytes | Ty::Buffer => {
                let _ = writeln!(out, "    thoxa_dup(e->{});", f.c_name);
            }
            Ty::Array { .. } => {
                let _ = writeln!(out, "    thoxa_array_dup(e->{});", f.c_name);
            }
            _ => {}
        }
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out, "static void {drop}(void *p) {{");
    let _ = writeln!(out, "    {cty} *e = ({cty} *)p;");
    for f in &layout.fields {
        if !needs_drop_ty(&f.ty) {
            continue;
        }
        match &f.ty {
            Ty::String | Ty::Bytes | Ty::Buffer => {
                let _ = writeln!(out, "    thoxa_drop(e->{});", f.c_name);
            }
            Ty::Array { .. } => {
                let _ = writeln!(out, "    thoxa_array_drop(e->{});", f.c_name);
            }
            _ => {}
        }
    }
    let _ = writeln!(out, "}}");
}

fn collect_user_array_elems_program(program: &Program, out: &mut Vec<String>) {
    for f in &program.functions {
        collect_user_array_elems_stmts(&f.body, out);
        push_user_array_elem(&f.ret_ty, out);
        for (_, ty) in &f.params {
            push_user_array_elem(ty, out);
        }
        if let Some((_, ty)) = &f.receiver {
            push_user_array_elem(ty, out);
        }
    }
    collect_user_array_elems_stmts(&program.init, out);
    for g in &program.globals {
        push_user_array_elem(&g.ty, out);
    }
}

fn collect_user_array_elems_stmts(stmts: &[Stmt], out: &mut Vec<String>) {
    for s in stmts {
        match s {
            Stmt::Assign { ty, value, .. } => {
                push_user_array_elem(ty, out);
                match value {
                    RValue::ArrayLit { elem_ty, .. }
                    | RValue::ArrayGet { elem_ty, .. }
                    | RValue::ArrayAppend { elem_ty, .. }
                    | RValue::ArrayDropLast { elem_ty, .. } => {
                        push_user_array_elem_ty(elem_ty, out);
                    }
                    _ => {}
                }
            }
            Stmt::DynIndexAssign { elem_ty, .. } => {
                push_user_array_elem_ty(elem_ty, out);
            }
            Stmt::Dup { ty, .. } | Stmt::Drop { ty, .. } => push_user_array_elem(ty, out),
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_user_array_elems_stmts(then_body, out);
                collect_user_array_elems_stmts(else_body, out);
            }
            Stmt::Loop { body } => collect_user_array_elems_stmts(body, out),
            Stmt::ForRange { body, .. } => collect_user_array_elems_stmts(body, out),
            _ => {}
        }
    }
}

fn push_user_array_elem(ty: &Ty, out: &mut Vec<String>) {
    if let Ty::Array { elem } = ty {
        push_user_array_elem_ty(elem, out);
    }
}

fn push_user_array_elem_ty(elem_ty: &Ty, out: &mut Vec<String>) {
    if let Ty::User(name) = elem_ty {
        if !out.iter().any(|n| n == name) {
            out.push(name.clone());
        }
    }
}

fn emit_rc(
    out: &mut String,
    pad: &str,
    place: &crate::mir::Place,
    ty: &Ty,
    dup: bool,
    types: &[TypeLayout],
) {
    let op = if dup { "thoxa_dup" } else { "thoxa_drop" };
    match ty {
        Ty::String | Ty::Bytes | Ty::Buffer => {
            let _ = writeln!(out, "{pad}{op}({});", place.name);
        }
        Ty::Array { elem } => {
            // Array drop walks heap elements; User uses field-level RC callbacks (D65).
            // Dup only bumps the array object (elements stay with the shared object).
            if dup {
                let _ = writeln!(out, "{pad}thoxa_array_dup({});", place.name);
            } else if let Ty::User(type_name) = elem.as_ref() {
                let _ = writeln!(
                    out,
                    "{pad}thoxa_array_drop_ex({}, {});",
                    place.name,
                    array_user_elem_drop_fn(type_name)
                );
            } else {
                let _ = writeln!(out, "{pad}thoxa_array_drop({});", place.name);
            }
        }
        Ty::User(name) => {
            let Some(layout) = types.iter().find(|t| t.name == *name) else {
                return;
            };
            for f in &layout.fields {
                if !needs_drop_ty(&f.ty) {
                    continue;
                }
                let nested = crate::mir::Place {
                    name: format!("{}.{}", place.name, f.c_name),
                };
                emit_rc(out, pad, &nested, &f.ty, dup, types);
            }
        }
        Ty::Trial { ok, err } => {
            let ok_d = needs_drop_ty(ok);
            let err_d = needs_drop_ty(err);
            if !ok_d && !err_d {
                return;
            }
            let _ = writeln!(out, "{pad}if ({}.tag == 0) {{", place.name);
            if ok_d {
                let nested = crate::mir::Place {
                    name: format!("{}.ok", place.name),
                };
                emit_rc(out, &format!("{pad}    "), &nested, ok, dup, types);
            }
            let _ = writeln!(out, "{pad}}} else {{");
            if err_d {
                let nested = crate::mir::Place {
                    name: format!("{}.err", place.name),
                };
                emit_rc(out, &format!("{pad}    "), &nested, err, dup, types);
            }
            let _ = writeln!(out, "{pad}}}");
        }
        _ => {}
    }
}

fn collect_trial_tys_program(program: &Program, out: &mut Vec<Ty>) {
    for f in &program.functions {
        collect_trial_tys_stmts(&f.body, out);
        push_trial_ty(&f.ret_ty, out);
        for (_, ty) in &f.params {
            push_trial_ty(ty, out);
        }
        if let Some((_, ty)) = &f.receiver {
            push_trial_ty(ty, out);
        }
    }
    collect_trial_tys_stmts(&program.init, out);
    for g in &program.globals {
        push_trial_ty(&g.ty, out);
    }
}

fn collect_trial_tys_stmts(stmts: &[Stmt], out: &mut Vec<Ty>) {
    for s in stmts {
        match s {
            Stmt::Assign { ty, value, .. } => {
                push_trial_ty(ty, out);
                if let RValue::TrialMake { trial_ty, .. } = value {
                    push_trial_ty(trial_ty, out);
                }
            }
            Stmt::Dup { ty, .. } | Stmt::Drop { ty, .. } => push_trial_ty(ty, out),
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_trial_tys_stmts(then_body, out);
                collect_trial_tys_stmts(else_body, out);
            }
            Stmt::Loop { body } => collect_trial_tys_stmts(body, out),
            Stmt::ForRange { body, .. } => collect_trial_tys_stmts(body, out),
            _ => {}
        }
    }
}

fn push_trial_ty(ty: &Ty, out: &mut Vec<Ty>) {
    if let Ty::Trial { .. } = ty {
        if !out.iter().any(|t| t == ty) {
            out.push(ty.clone());
        }
    }
}

fn c_type_name(thoxa: &str) -> String {
    format!("Thoxa_{thoxa}")
}

fn c_free_fn_name(thoxa_name: &str) -> String {
    if thoxa_name == "main" {
        "thoxa_fn_main".to_string()
    } else {
        format!("thoxa_fn_{thoxa_name}")
    }
}

fn c_method_name(type_name: &str, method: &str) -> String {
    format!("thoxa_m_{type_name}_{method}")
}

fn c_fn_name(f: &Function) -> String {
    if let Some((ty, method)) = f.name.split_once("__") {
        if f.receiver.is_some() {
            return c_method_name(ty, method);
        }
    }
    c_free_fn_name(&f.name)
}
