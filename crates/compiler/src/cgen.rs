//! MIR → C source.

use crate::ast::{BinaryOp, UnaryOp};
use crate::mir::{Callee, Function, Program, RValue, Stmt, Ty};
use std::collections::HashSet;
use std::fmt::Write as _;

pub fn emit_program(program: &Program) -> String {
    let mut out = String::new();
    out.push_str("/* Generated by thoxa — do not edit */\n");
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include <stdbool.h>\n");
    out.push_str("#include \"thoxa_rt.h\"\n\n");

    for f in &program.functions {
        emit_function(&mut out, f);
        out.push('\n');
    }

    out.push_str("int main(void) {\n");
    out.push_str("    return (int)thoxa_fn_main();\n");
    out.push_str("}\n");
    out
}

fn emit_function(out: &mut String, f: &Function) {
    let c_name = c_fn_name(&f.name);
    let ret = c_ty(f.ret_ty);
    let _ = writeln!(out, "{ret} {c_name}(void) {{");

    // Collect locals
    let mut locals: Vec<(String, Ty)> = Vec::new();
    let mut seen = HashSet::new();
    collect_locals(&f.body, &mut locals, &mut seen);
    if let Some(ref r) = f.ret {
        if seen.insert(r.name.clone()) {
            locals.push((r.name.clone(), f.ret_ty));
        }
    }

    for (name, ty) in &locals {
        if *ty == Ty::Void {
            continue;
        }
        let _ = writeln!(out, "    {} {};", c_ty(*ty), name);
    }

    emit_stmts(out, &f.body, 1);

    match (&f.ret, f.ret_ty) {
        (Some(p), Ty::Int64) | (Some(p), Ty::Bool) => {
            let _ = writeln!(out, "    return {};", p.name);
        }
        (None, Ty::Void) => {}
        _ => {
            out.push_str("    return 0;\n");
        }
    }
    out.push_str("}\n");
}

fn collect_locals(stmts: &[Stmt], locals: &mut Vec<(String, Ty)>, seen: &mut HashSet<String>) {
    for s in stmts {
        match s {
            Stmt::Assign { place, ty, .. } => {
                if seen.insert(place.name.clone()) {
                    locals.push((place.name.clone(), *ty));
                }
            }
            Stmt::Eval(_) => {}
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_locals(then_body, locals, seen);
                collect_locals(else_body, locals, seen);
            }
        }
    }
}

fn emit_stmts(out: &mut String, stmts: &[Stmt], indent: usize) {
    let pad = "    ".repeat(indent);
    for s in stmts {
        match s {
            Stmt::Assign { place, value, .. } => {
                let _ = write!(out, "{pad}{} = ", place.name);
                emit_rvalue(out, value);
                out.push_str(";\n");
            }
            Stmt::Eval(rv) => {
                let _ = write!(out, "{pad}");
                emit_rvalue(out, rv);
                out.push_str(";\n");
            }
            Stmt::If {
                cond,
                then_body,
                else_body,
            } => {
                let _ = writeln!(out, "{pad}if ({}) {{", cond.name);
                emit_stmts(out, then_body, indent + 1);
                if else_body.is_empty() {
                    let _ = writeln!(out, "{pad}}}");
                } else {
                    let _ = writeln!(out, "{pad}}} else {{");
                    emit_stmts(out, else_body, indent + 1);
                    let _ = writeln!(out, "{pad}}}");
                }
            }
        }
    }
}

fn emit_rvalue(out: &mut String, rv: &RValue) {
    match rv {
        RValue::Use(p) => {
            out.push_str(&p.name);
        }
        RValue::Int(n) => {
            let _ = write!(out, "INT64_C({n})");
        }
        RValue::Bool(b) => {
            out.push_str(if *b { "true" } else { "false" });
        }
        RValue::Str(s) => {
            emit_c_string(out, s);
        }
        RValue::Unary { op, arg } => match op {
            UnaryOp::Neg => {
                let _ = write!(out, "-({})", arg.name);
            }
            UnaryOp::Not => {
                let _ = write!(out, "!({})", arg.name);
            }
        },
        RValue::Binary { op, left, right } => {
            let opc = match op {
                BinaryOp::Add => "+",
                BinaryOp::Sub => "-",
                BinaryOp::Mul => "*",
                BinaryOp::Div => "/",
                BinaryOp::Rem => "%",
                BinaryOp::Eq => "==",
                BinaryOp::Ne => "!=",
                BinaryOp::Lt => "<",
                BinaryOp::Le => "<=",
                BinaryOp::Gt => ">",
                BinaryOp::Ge => ">=",
                BinaryOp::And => "&&",
                BinaryOp::Or => "||",
            };
            let _ = write!(out, "({}) {} ({})", left.name, opc, right.name);
        }
        RValue::Call { callee, args } => match callee {
            Callee::Builtin(name) => {
                let c = match name.as_str() {
                    "println" => "thoxa_println",
                    "print" => "thoxa_print",
                    "println_i64" => "thoxa_println_i64",
                    "print_i64" => "thoxa_print_i64",
                    "println_bool" => "thoxa_println_bool",
                    "print_bool" => "thoxa_print_bool",
                    other => other,
                };
                out.push_str(c);
                out.push('(');
                for (i, a) in args.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    out.push_str(&a.name);
                }
                out.push(')');
            }
        },
    }
}

fn emit_c_string(out: &mut String, s: &str) {
    out.push('\"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            '\0' => out.push_str("\\0"),
            c if c.is_control() => {
                let _ = write!(out, "\\x{:02x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('\"');
}

fn c_ty(ty: Ty) -> &'static str {
    match ty {
        Ty::Int64 => "int64_t",
        Ty::Bool => "bool",
        Ty::CStr => "const char*",
        Ty::Void => "void",
    }
}

fn c_fn_name(thoxa_name: &str) -> String {
    if thoxa_name == "main" {
        "thoxa_fn_main".to_string()
    } else {
        format!("thoxa_fn_{thoxa_name}")
    }
}

