//! MIR → C source.

use crate::mir::{Callee, Function, Operand, Program, RValue, Stmt, Ty};
use std::fmt::Write as _;

pub fn emit_program(program: &Program) -> String {
    let mut out = String::new();
    out.push_str("/* Generated by thoxa — do not edit */\n");
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include \"thoxa_rt.h\"\n\n");

    for f in &program.functions {
        emit_function(&mut out, f);
        out.push('\n');
    }

    // C entry: call Thoxa main, use return as exit code.
    out.push_str("int main(void) {\n");
    out.push_str("    return (int)thoxa_fn_main();\n");
    out.push_str("}\n");
    out
}

fn emit_function(out: &mut String, f: &Function) {
    let c_name = c_fn_name(&f.name);
    let ret = match f.ret_ty {
        Ty::Int64 => "int64_t",
        Ty::Void => "void",
    };
    let _ = writeln!(out, "{ret} {c_name}(void) {{");
    for stmt in &f.body {
        match stmt {
            Stmt::Eval(rv) => {
                out.push_str("    ");
                emit_rvalue(out, rv);
                out.push_str(";\n");
            }
        }
    }
    match (&f.ret, f.ret_ty) {
        (Some(op), Ty::Int64) => {
            out.push_str("    return ");
            emit_operand(out, op);
            out.push_str(";\n");
        }
        (None, Ty::Void) => {}
        _ => {
            out.push_str("    return 0;\n");
        }
    }
    out.push_str("}\n");
}

fn emit_rvalue(out: &mut String, rv: &RValue) {
    match rv {
        RValue::Call { callee, args } => match callee {
            Callee::Builtin(name) => {
                let c = match name.as_str() {
                    "println" => "thoxa_println",
                    "print" => "thoxa_print",
                    other => other,
                };
                out.push_str(c);
                out.push('(');
                for (i, a) in args.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    emit_operand(out, a);
                }
                out.push(')');
            }
        },
    }
}

fn emit_operand(out: &mut String, op: &Operand) {
    match op {
        Operand::Int(n) => {
            let _ = write!(out, "INT64_C({n})");
        }
        Operand::Str(s) => {
            out.push('\"');
            for ch in s.chars() {
                match ch {
                    '\\' => out.push_str("\\\\"),
                    '"' => out.push_str("\\\""),
                    '\n' => out.push_str("\\n"),
                    '\t' => out.push_str("\\t"),
                    '\r' => out.push_str("\\r"),
                    '\0' => out.push_str("\\0"),
                    c if c.is_control() => {
                        let _ = write!(out, "\\x{:02x}", c as u32);
                    }
                    c => out.push(c),
                }
            }
            out.push('\"');
        }
    }
}

fn c_fn_name(thoxa_name: &str) -> String {
    if thoxa_name == "main" {
        "thoxa_fn_main".to_string()
    } else {
        format!("thoxa_fn_{thoxa_name}")
    }
}
