/// Static field-walk helpers used as ThoxaArrayElemFn for Array<User>.
/// Elements may have String/Bytes/Node/Array/Map and nested User fields.
/// Recursive Array<T> uses the forward-declared helpers above.
fn emit_array_user_elem_rc(out: &mut String, layout: &TypeLayout, types: &[TypeLayout]) {
    // A `drop` type's slot holds its box pointer (D155).
    let cty = c_val_ty(&Ty::User(layout.name.clone()), types);
    let dup = array_user_elem_dup_fn(&layout.name);
    let drop = array_user_elem_drop_fn(&layout.name);
    let _ = writeln!(out, "static void {dup}(void *p) {{");
    let _ = writeln!(out, "    {cty} *e = ({cty} *)p;");
    emit_array_user_elem_fields(out, layout, types, true);
    let _ = writeln!(out, "}}");
    let _ = writeln!(out, "static void {drop}(void *p) {{");
    let _ = writeln!(out, "    {cty} *e = ({cty} *)p;");
    emit_array_user_elem_fields(out, layout, types, false);
    let _ = writeln!(out, "}}");
}

fn emit_array_user_elem_fields(
    out: &mut String,
    layout: &TypeLayout,
    types: &[TypeLayout],
    dup: bool,
) {
    // Sums (Json) have no product fields; walk the live arm via emit_rc.
    // Products keep the same field RC as before (`(*e).field`).
    let nested = crate::mir::Place {
        name: "(*e)".into(),
    };
    emit_rc(
        out,
        "    ",
        &nested,
        &Ty::User(layout.name.clone()),
        dup,
        types,
    );
}

fn collect_user_array_elems_program(program: &Program, out: &mut Vec<String>) {
    // Type layouts may carry Array<User> fields (e.g. Request.headers) even when a
    // function only drops the outer User without an explicit Array op — emit helpers.
    for t in &program.types {
        for f in &t.fields {
            push_user_array_elem(&f.ty, out);
        }
    }
    for f in &program.functions {
        collect_user_array_elems_stmts(&f.body, out);
        push_user_array_elem(&f.ret_ty, out);
        for (_, ty) in &f.params {
            push_user_array_elem(ty, out);
        }
        if let Some((_, ty)) = &f.receiver {
            push_user_array_elem(ty, out);
        }
    }
    collect_user_array_elems_stmts(&program.init, out);
    for g in &program.globals {
        push_user_array_elem(&g.ty, out);
    }
}

fn push_user_array_elem_from_rvalue(rv: &RValue, out: &mut Vec<String>) {
    match rv {
        RValue::ArrayLit { elem_ty, .. }
        | RValue::ArrayGet { elem_ty, .. }
        | RValue::ArrayAppend { elem_ty, .. }
        | RValue::ArrayDropLast { elem_ty, .. }
        | RValue::ArrayInsertAt { elem_ty, .. }
        | RValue::ArrayRemoveAt { elem_ty, .. } => {
            push_user_array_elem_ty(elem_ty, out);
        }
        RValue::MapNew { val_ty, .. }
        | RValue::MapSet { val_ty, .. }
        | RValue::MapRemove { val_ty, .. }
        | RValue::MapGet { val_ty, .. }
        | RValue::MapValAt { val_ty, .. }
        | RValue::MapValues { val_ty, .. } => {
            push_user_array_elem_ty(val_ty, out);
        }
        _ => {}
    }
}

fn collect_user_array_elems_stmts(stmts: &[Stmt], out: &mut Vec<String>) {
    for s in stmts {
        match s {
            Stmt::Assign { ty, value, .. } => {
                push_user_array_elem(ty, out);
                push_user_array_elem_from_rvalue(value, out);
            }
            Stmt::Eval(rv) => {
                push_user_array_elem_from_rvalue(rv, out);
            }
            Stmt::DynIndexAssign { elem_ty, .. } => {
                push_user_array_elem_ty(elem_ty, out);
            }
            Stmt::Dup { ty, .. } | Stmt::Drop { ty, .. } => push_user_array_elem(ty, out),
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_user_array_elems_stmts(then_body, out);
                collect_user_array_elems_stmts(else_body, out);
            }
            Stmt::Loop { body } => collect_user_array_elems_stmts(body, out),
            Stmt::ForRange { body, .. } => collect_user_array_elems_stmts(body, out),
            _ => {}
        }
    }
}

fn push_user_array_elem(ty: &Ty, out: &mut Vec<String>) {
    if let Ty::Array { elem } = ty {
        push_user_array_elem_ty(elem, out);
    }
    if let Ty::Map { val, .. } = ty {
        push_user_array_elem_ty(val, out);
    }
}

fn push_user_array_elem_ty(elem_ty: &Ty, out: &mut Vec<String>) {
    if let Ty::User(name) = elem_ty {
        if !out.iter().any(|n| n == name) {
            out.push(name.clone());
        }
    }
}

/// Zero a heap place without dropping (ownership already transferred).
fn emit_clear_place(
    out: &mut String,
    pad: &str,
    place: &crate::mir::Place,
    ty: &Ty,
    types: &[TypeLayout],
) {
    if is_boxed_user(ty, types)
        || matches!(
            ty,
            Ty::String | Ty::Bytes | Ty::Buffer | Ty::Node | Ty::Array { .. } | Ty::Map { .. }
        )
    {
        let _ = writeln!(out, "{pad}{} = NULL;", place.name);
        return;
    }
    match ty {
        Ty::Fn { .. } => {
            let _ = writeln!(out, "{pad}{} = (ThoxaFn){{0}};", place.name);
        }
        Ty::User(_) => {
            let _ = writeln!(out, "{pad}{} = ({}){{0}};", place.name, c_ty(ty));
        }
        _ => {}
    }
}

fn emit_rc(
    out: &mut String,
    pad: &str,
    place: &crate::mir::Place,
    ty: &Ty,
    dup: bool,
    types: &[TypeLayout],
) {
    let op = if dup { "thoxa_dup" } else { "thoxa_drop" };
    match ty {
        Ty::String | Ty::Bytes | Ty::Buffer | Ty::Node => {
            let _ = writeln!(out, "{pad}{op}({});", place.name);
            if !dup {
                let _ = writeln!(out, "{pad}{} = NULL;", place.name);
            }
        }
        Ty::Map { val, .. } => {
            if dup {
                let _ = writeln!(out, "{pad}thoxa_map_dup({});", place.name);
            } else if let Ty::User(type_name) = val.as_ref() {
                let _ = writeln!(
                    out,
                    "{pad}thoxa_map_drop_ex({}, {});",
                    place.name,
                    array_user_elem_drop_fn(type_name)
                );
                let _ = writeln!(out, "{pad}{} = NULL;", place.name);
            } else {
                let _ = writeln!(out, "{pad}thoxa_map_drop({});", place.name);
                let _ = writeln!(out, "{pad}{} = NULL;", place.name);
            }
        }
        Ty::Array { elem } => {
            // Array drop walks heap elements; User uses field-level RC callbacks (D65).
            // Dup only bumps the array object (elements stay with the shared object).
            if dup {
                let _ = writeln!(out, "{pad}thoxa_array_dup({});", place.name);
            } else if let Ty::User(type_name) = elem.as_ref() {
                let _ = writeln!(
                    out,
                    "{pad}thoxa_array_drop_ex({}, {});",
                    place.name,
                    array_user_elem_drop_fn(type_name)
                );
                let _ = writeln!(out, "{pad}{} = NULL;", place.name);
            } else {
                let _ = writeln!(out, "{pad}thoxa_array_drop({});", place.name);
                let _ = writeln!(out, "{pad}{} = NULL;", place.name);
            }
        }
        Ty::Fn { .. } => {
            if dup {
                let _ = writeln!(out, "{pad}thoxa_fn_retain(&{});", place.name);
            } else {
                let _ = writeln!(out, "{pad}thoxa_fn_release(&{});", place.name);
            }
        }
        Ty::User(name) => {
            let Some(layout) = types.iter().find(|t| t.name == *name) else {
                return;
            };
            if layout.has_drop {
                let _ = writeln!(out, "{pad}{op}({});", place.name);
                if !dup {
                    let _ = writeln!(out, "{pad}{} = NULL;", place.name);
                }
                return;
            }
            // Tagged sum: only the live arm's payload participates (D118 heap payloads).
            if let Some(variants) = &layout.sum {
                let any = variants.iter().any(|v| needs_drop_ty(&v.payload_ty));
                if !any {
                    return;
                }
                // Nest if/else on tag (same shape as union match).
                let mut first = true;
                for v in variants {
                    if !needs_drop_ty(&v.payload_ty) {
                        continue;
                    }
                    if first {
                        let _ = writeln!(out, "{pad}if ({}.tag == {}) {{", place.name, v.tag);
                        first = false;
                    } else {
                        let _ =
                            writeln!(out, "{pad}}} else if ({}.tag == {}) {{", place.name, v.tag);
                    }
                    let nested = crate::mir::Place {
                        name: format!("{}.u.v{}", place.name, v.tag),
                    };
                    emit_rc(
                        out,
                        &format!("{pad}    "),
                        &nested,
                        &v.payload_ty,
                        dup,
                        types,
                    );
                }
                if !first {
                    let _ = writeln!(out, "{pad}}}");
                }
                return;
            }
            for f in &layout.fields {
                if !needs_drop_ty(&f.ty) {
                    continue;
                }
                let nested = crate::mir::Place {
                    name: format!("{}.{}", place.name, f.c_name),
                };
                emit_rc(out, pad, &nested, &f.ty, dup, types);
            }
        }
        _ => {}
    }
}

fn c_type_name(thoxa: &str) -> String {
    format!("Thoxa_{thoxa}")
}

fn c_free_fn_name(thoxa_name: &str) -> String {
    if thoxa_name == "main" {
        "thoxa_fn_main".to_string()
    } else {
        format!("thoxa_fn_{thoxa_name}")
    }
}

fn c_method_name(type_name: &str, method: &str) -> String {
    format!("thoxa_m_{type_name}_{method}")
}

/// Method receiver `_self` is a pointer (D107); Drop boxes are pointers too (D155).
fn recv_access(base: &crate::mir::Place, boxed: &HashSet<String>) -> &'static str {
    if base.name == "_self" || boxed.contains(&base.name) {
        "->"
    } else {
        "."
    }
}

fn c_fn_name(f: &Function) -> String {
    // Method names are `{type}__{method}`; monomorph types may contain `__`
    // (`Box__Int64__get`), so split from the right.
    if f.receiver.is_some() {
        if let Some((ty, method)) = f.name.rsplit_once("__") {
            return c_method_name(ty, method);
        }
    }
    c_free_fn_name(&f.name)
}

fn thunk_c_name(target: &FnTarget) -> String {
    match target {
        FnTarget::Free { mangled } => format!("thoxa_fnptr_free_{mangled}"),
        FnTarget::Method {
            type_name,
            method,
            bound: true,
        } => format!("thoxa_fnptr_bound_{type_name}_{method}"),
        FnTarget::Method {
            type_name,
            method,
            bound: false,
        } => format!("thoxa_fnptr_unbound_{type_name}_{method}"),
    }
}

fn fn_payload_retain_name(type_name: &str) -> String {
    format!("thoxa_fn_retain_payload_{type_name}")
}

fn fn_payload_release_name(type_name: &str) -> String {
    format!("thoxa_fn_release_payload_{type_name}")
}

fn emit_fn_support(out: &mut String, program: &Program, types: &[TypeLayout]) {
    let mut thunks: Vec<FnTarget> = Vec::new();
    let mut recvs: Vec<String> = Vec::new();
    collect_fn_targets_stmts(&program.init, &mut thunks, &mut recvs);
    for f in &program.functions {
        collect_fn_targets_stmts(&f.body, &mut thunks, &mut recvs);
    }
    thunks.sort_by(|a, b| thunk_c_name(a).cmp(&thunk_c_name(b)));
    thunks.dedup();
    recvs.sort();
    recvs.dedup();

    for tn in &recvs {
        emit_fn_payload_rc(out, tn, types);
    }
    for t in &thunks {
        emit_fn_thunk(out, t, program);
    }
}

fn emit_fn_payload_rc(out: &mut String, type_name: &str, types: &[TypeLayout]) {
    if is_boxed_user_name(type_name, types) {
        let _ = writeln!(
            out,
            "static void {}(void *p) {{",
            fn_payload_retain_name(type_name)
        );
        out.push_str("    thoxa_dup(*(void **)p);\n}\n");
        let _ = writeln!(
            out,
            "static void {}(void *p) {{",
            fn_payload_release_name(type_name)
        );
        out.push_str("    thoxa_drop(*(void **)p);\n    *(void **)p = NULL;\n}\n");
        return;
    }
    let cty = c_type_name(type_name);
    let _ = writeln!(
        out,
        "static void {}(void *p) {{",
        fn_payload_retain_name(type_name)
    );
    let _ = writeln!(out, "    {cty} *_s = ({cty} *)p;");
    emit_rc(
        out,
        "    ",
        &crate::mir::Place {
            name: "(*_s)".into(),
        },
        &Ty::User(type_name.to_string()),
        true,
        types,
    );
    out.push_str("}\n");
    let _ = writeln!(
        out,
        "static void {}(void *p) {{",
        fn_payload_release_name(type_name)
    );
    let _ = writeln!(out, "    {cty} *_s = ({cty} *)p;");
    emit_rc(
        out,
        "    ",
        &crate::mir::Place {
            name: "(*_s)".into(),
        },
        &Ty::User(type_name.to_string()),
        false,
        types,
    );
    out.push_str("}\n");
}

fn emit_fn_thunk(out: &mut String, target: &FnTarget, program: &Program) {
    match target {
        FnTarget::Free { mangled } => {
            if mangled.is_empty() {
                return;
            }
            let Some(f) = program.functions.iter().find(|f| f.name == *mangled) else {
                return;
            };
            emit_thunk_sig(
                out,
                &thunk_c_name(target),
                &f.params,
                &f.ret_ty,
                &program.types,
            );
            out.push_str("    (void)recv;\n");
            emit_thunk_invoke(
                out,
                &c_free_fn_name(mangled),
                &f.params,
                &f.ret_ty,
                false,
                &program.types,
            );
            out.push_str("}\n");
        }
        FnTarget::Method {
            type_name,
            method,
            bound,
        } => {
            let Some(f) = program.functions.iter().find(|f| {
                f.receiver
                    .as_ref()
                    .is_some_and(|(_, t)| matches!(t, Ty::User(n) if n == type_name))
                    && f.name.rsplit_once("__").is_some_and(|(_, m)| m == method)
            }) else {
                return;
            };
            if *bound {
                emit_thunk_sig(
                    out,
                    &thunk_c_name(target),
                    &f.params,
                    &f.ret_ty,
                    &program.types,
                );
                let cty = c_type_name(type_name);
                if is_boxed_user_name(type_name, &program.types) {
                    let _ = writeln!(
                        out,
                        "    {cty} *_self = *({cty} **)thoxa_fn_payload((ThoxaFnBox *)recv);"
                    );
                } else {
                    let _ = writeln!(
                        out,
                        "    {cty} *_self = ({cty} *)thoxa_fn_payload((ThoxaFnBox *)recv);"
                    );
                }
                if f.ret_ty == Ty::Void || f.ret_ty == Ty::Never {
                    let _ = write!(out, "    {}(_self", c_method_name(type_name, method));
                } else {
                    let _ = write!(out, "    return {}(_self", c_method_name(type_name, method));
                }
                for (n, _) in &f.params {
                    let _ = write!(out, ", {n}");
                }
                out.push_str(");\n");
            } else {
                let mut params = Vec::new();
                if let Some((n, t)) = &f.receiver {
                    params.push((n.clone(), t.clone()));
                }
                params.extend(f.params.iter().cloned());
                emit_thunk_sig(
                    out,
                    &thunk_c_name(target),
                    &params,
                    &f.ret_ty,
                    &program.types,
                );
                out.push_str("    (void)recv;\n");
                emit_thunk_invoke(
                    out,
                    &c_method_name(type_name, method),
                    &params,
                    &f.ret_ty,
                    true,
                    &program.types,
                );
            }
            out.push_str("}\n");
        }
    }
}

fn emit_thunk_sig(
    out: &mut String,
    name: &str,
    params: &[(String, Ty)],
    ret: &Ty,
    types: &[TypeLayout],
) {
    let r = if *ret == Ty::Void || *ret == Ty::Never {
        "void".to_string()
    } else {
        c_val_ty(ret, types)
    };
    let _ = write!(out, "static {r} {name}(void *recv");
    for (n, t) in params {
        let _ = write!(out, ", {} {}", c_val_ty(t, types), n);
    }
    out.push_str(") {\n");
}

fn emit_thunk_invoke(
    out: &mut String,
    c_name: &str,
    params: &[(String, Ty)],
    ret: &Ty,
    first_user_is_self_ptr: bool,
    types: &[TypeLayout],
) {
    if *ret == Ty::Void || *ret == Ty::Never {
        let _ = write!(out, "    {c_name}(");
    } else {
        let _ = write!(out, "    return {c_name}(");
    }
    for (i, (n, t)) in params.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        if i == 0
            && first_user_is_self_ptr
            && matches!(t, Ty::User(_))
            && !is_boxed_user(t, types)
        {
            let _ = write!(out, "&{n}");
        } else {
            out.push_str(n);
        }
    }
    out.push_str(");\n");
}

fn collect_fn_targets_stmts(stmts: &[Stmt], thunks: &mut Vec<FnTarget>, recvs: &mut Vec<String>) {
    for s in stmts {
        match s {
            Stmt::Assign { value, .. } => collect_fn_targets_rvalue(value, thunks, recvs),
            Stmt::Eval(v) => collect_fn_targets_rvalue(v, thunks, recvs),
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_fn_targets_stmts(then_body, thunks, recvs);
                collect_fn_targets_stmts(else_body, thunks, recvs);
            }
            Stmt::Loop { body } | Stmt::ForRange { body, .. } => {
                collect_fn_targets_stmts(body, thunks, recvs);
            }
            _ => {}
        }
    }
}

fn collect_fn_targets_rvalue(v: &RValue, thunks: &mut Vec<FnTarget>, recvs: &mut Vec<String>) {
    if let RValue::MakeFn {
        recv_ty, target, ..
    } = v
    {
        thunks.push(target.clone());
        if let Some(Ty::User(n)) = recv_ty {
            recvs.push(n.clone());
        }
    }
}
